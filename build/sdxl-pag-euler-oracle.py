# sdxl-pag-euler-oracle.py -- three guided Euler steps of SDXL with PAG as the paper and
# diffusers apply it at every step, written out as the Codex chapter
# codex/test/apps/sdxl-pag-euler is graded against.
#
#   D:\AI\DiffusionForge\system\python\python.exe build/sdxl-pag-euler-oracle.py <checkpoint> <out.codex>
#
# The denoiser is k-diffusion's DiscreteEpsDDPMDenoiser over Forge's UNet in float32 (as
# build/sdxl-unet-oracle.py's Euler reference); guidance is uncond + cfg (cond - uncond)
# + scale (cond - perturbed), the form of diffusers' StableDiffusionXLPAGPipeline, whose
# PAGIdentitySelfAttnProcessor2_0 answers the value projection for every self-attention of
# the mid block. The perturbation is Forge's patches_replace keyed ("middle", 0), made fresh
# for each call. Arms: pag (as intended), forge (as Forge's sd_forge_perturbed_attention
# runs past its first call: its write-back leaves the patch in the sampler's model options,
# so every later cond and uncond call is perturbed and the PAG term is 0), plain (no PAG).
import inspect, math, os, sys
import numpy as np
import torch

WEBUI = r'D:\AI\DiffusionForge\webui'
sys.path[:0] = [WEBUI, os.path.join(WEBUI, 'repositories', 'huggingface_guess'), os.path.join(WEBUI, 'packages_3rdparty')]
H = W = 16
CFG = 5.0
PAG = 3.0
STEPS = 3
PREFIX = 'model.diffusion_model.'

def noise(i): return ((i * 53 + 17) % 263 - 131) / 128.0
def context_c(i): return ((i * 13 + 5) % 251 - 125) / 256.0
def label_c(i): return ((i * 29 + 3) % 241 - 120) / 256.0
def context_u(i): return ((i * 17 + 3) % 239 - 119) / 256.0
def label_u(i): return ((i * 23 + 7) % 233 - 116) / 256.0

def real(v):
    s = np.format_float_positional(np.float32(v), unique=True, trim='0')
    if s.endswith('.'): s += '0'
    return '(0.0 - ' + s[1:] + ')' if s.startswith('-') else s

def main():
    ckpt, out = sys.argv[1], sys.argv[2]
    sys.argv = sys.argv[:1]
    from safetensors import safe_open
    from huggingface_guess import detection
    from backend.nn.unet import IntegratedUNet2DConditionModel
    from k_diffusion import external, sampling

    with safe_open(ckpt, framework='pt') as f:
        keys = [k for k in f.keys() if k.startswith(PREFIX)]
        cfg = detection.detect_unet_config({k: torch.empty(f.get_slice(k).get_shape(), device='meta') for k in keys}, PREFIX)
        cfg['num_heads'] = -1
        cfg['num_head_channels'] = 64
        accepted = inspect.signature(IntegratedUNet2DConditionModel.__init__).parameters
        for k in [k for k in cfg if k not in accepted]:
            del cfg[k]
        with torch.device('cuda'):
            model = IntegratedUNet2DConditionModel(**cfg).float().eval()
        params = model.state_dict()
        with torch.no_grad():
            for k in keys:
                params[k[len(PREFIX):]].copy_(f.get_tensor(k).to('cuda'))

    conds = {'c': (torch.tensor([context_c(i) for i in range(77 * 2048)]).reshape(1, 77, 2048).cuda(), torch.tensor([label_c(i) for i in range(2816)]).reshape(1, 2816).cuda()),
             'u': (torch.tensor([context_u(i) for i in range(77 * 2048)]).reshape(1, 77, 2048).cuda(), torch.tensor([label_u(i) for i in range(2816)]).reshape(1, 2816).cuda())}

    class Eps(torch.nn.Module):
        def forward(self, x, t, which=None, perturb=False):
            ctx, y = conds[which]
            to = {'patches_replace': {'attn1': {('middle', 0): lambda q, k, v, extra: v}}} if perturb else {}
            return model(x, timesteps=t, context=ctx, y=y, transformer_options=to)
    betas = torch.linspace(0.00085 ** 0.5, 0.012 ** 0.5, 1000, dtype=torch.float64) ** 2
    den = external.DiscreteEpsDDPMDenoiser(Eps(), torch.cumprod(1.0 - betas, dim=0).float().cuda(), quantize=True)
    sigmas = sampling.get_sigmas_karras(STEPS, float(den.sigma_min), float(den.sigma_max), device='cuda')

    def guided(arm):
        calls = [0]
        def d(x, s, **kw):
            first = calls[0] == 0
            calls[0] += 1
            if arm == 'plain':
                c, u = den(x, s, which='c'), den(x, s, which='u')
                return u + (c - u) * CFG
            if arm == 'forge' and not first:
                c, u = den(x, s, which='c', perturb=True), den(x, s, which='u', perturb=True)
                return u + (c - u) * CFG
            c, u, p = den(x, s, which='c'), den(x, s, which='u'), den(x, s, which='c', perturb=True)
            return u + (c - u) * CFG + (c - p) * PAG
        return d

    lines = ['Chapter: SdxlPagEulerReference', '',
             ' Generated by build/sdxl-pag-euler-oracle.py from %s: three Euler steps at' % os.path.basename(ckpt),
             ' CFG %s with PAG %s as intended, as Forge runs it past its first call, and without.' % (CFG, PAG),
             ' Regenerate, do not edit.', '', ' We say:', '', 'Section: Steps', '']
    for arm in ('pag', 'forge', 'plain'):
        x = torch.tensor([noise(i) for i in range(4 * H * W)], dtype=torch.float32).reshape(1, 4, H, W).cuda() * sigmas[0]
        d = guided(arm)
        with torch.no_grad():
            for i in range(STEPS):
                x = sampling.sample_euler(d, x, sigmas[i:i + 2], disable=True)
                v = x.reshape(-1).float().cpu().numpy().astype(np.float64)
                lines += ['  spe-%s-%d : List Real' % (arm, i), '  spe-%s-%d = [%s]' % (arm, i, ', '.join(real(t) for t in v)), '']
                print(arm, i, 'rms', math.sqrt((v * v).mean()))
    lines += ['Page 1', '']
    open(out, 'w', newline='\r\n').write('\n'.join(lines))

main()
