# flux-clip-oracle.py -- Flux's CLIP-L pooled output for one prompt, written
# as the Codex chapter apps/diffusion/FluxClipReference, which
# codex/test/apps/flux-condition grades apps/diffusion/FluxCondition against.
#
#   D:\AI\DiffusionForge\system\python\python.exe build/flux-clip-oracle.py <out.codex>
#
# transformers' CLIPTextModel (Forge's IntegratedCLIP wraps it) under
# FLUX.1-schnell's text_encoder/config.json over models/VAE/clip_l.safetensors
# (F16, keys under text_model.), in float32 and again in float16 on CUDA. The
# ids are Forge's first chunk (classic_engine.py): BOS 49406, PROMPT through
# FLUX.1-schnell's CLIPTokenizer, EOS 49407, padded with 49407 to 77. The
# pooled output is pooler_output, the final-normed hidden state at the first
# EOS, with no projection (flux.py: text_projection False). Written: the 768
# f32 values, and the f16 run's worst deviation from them over their rms.
import math, os, sys
import numpy as np
import torch

WEBUI = r'D:\AI\DiffusionForge\webui'
HF = os.path.join(WEBUI, r'backend\huggingface\black-forest-labs\FLUX.1-schnell')
CKPT = os.path.join(WEBUI, r'models\VAE\clip_l.safetensors')
PROMPT = 'a photo of a (red:1.3) apple on a [wooden] table, ((soft window light))'

def real(v):
    s = np.format_float_positional(np.float32(v), unique=True, trim='0')
    if s.endswith('.'): s += '0'
    return '(0.0 - ' + s[1:] + ')' if s.startswith('-') else s

def main():
    out = sys.argv[1]
    from transformers import CLIPTextConfig, CLIPTextModel, CLIPTokenizer
    from safetensors.torch import load_file
    tok = CLIPTokenizer.from_pretrained(os.path.join(HF, 'tokenizer'))
    words = PROMPT.replace('(red:1.3)', 'red').replace('[wooden]', 'wooden').replace('((soft window light))', 'soft window light')
    body = tok(words, add_special_tokens=False)['input_ids']
    ids = [49406] + body + [49407] * (77 - 1 - len(body))
    cfg = CLIPTextConfig.from_json_file(os.path.join(HF, 'text_encoder', 'config.json'))
    state = {k: v.float() for k, v in load_file(CKPT).items()}
    def pooled(dtype):
        m = CLIPTextModel(cfg)
        m.load_state_dict(state, strict=False)
        m = m.to('cuda', dtype).eval()
        with torch.no_grad():
            return m(input_ids=torch.tensor([ids]).cuda()).pooler_output[0].float().cpu().numpy().astype(np.float64)
    ref = pooled(torch.float32)
    half = pooled(torch.float16)
    rms = math.sqrt((ref * ref).mean())
    dev = float(np.abs(half - ref).max() / rms)
    lines = ['Chapter: FluxClipReference', '',
             ' Generated by build/flux-clip-oracle.py: Flux\'s CLIP-L pooled output (clip_l,',
             ' no projection) for one prompt, in float32. Regenerate, do not edit.', '',
             ' We say:', '', 'Section: Pooled', '',
             '  flux-clip-ref-prompt : Text = "%s"' % PROMPT, '',
             '  flux-clip-ref-ids : List Integer = [%s]' % ', '.join(str(i) for i in ids), '',
             '  flux-clip-ref-rms : Real = %s' % real(rms), '',
             '  flux-clip-ref-f16-dev : Real = %s' % real(dev), '',
             '  flux-clip-ref-pooled : List Real = [%s]' % ', '.join(real(v) for v in ref), '', 'Page 1', '']
    open(out, 'w', newline='\r\n').write('\n'.join(lines))
    print('ids', ids[:14], 'rms', rms, 'f16 deviation', dev)

main()
