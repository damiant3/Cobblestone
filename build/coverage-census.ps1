# coverage-census.ps1 -- what no test asks a question of. On demand, never a gate.
#
#   pwsh build/coverage-census.ps1 -Tree codex/foreword        # library coverage by area
#   pwsh build/coverage-census.ps1 -Tree apps/uoaix -List      # and every unreached chapter
#   pwsh build/coverage-census.ps1 -Diagnostics                # CDX codes no sidecar or sabotage row grades
#
# -Tree: a chapter is REACHED when a computing test cites it, directly or through
# the cite closure. A computing test is a chapter under codex/ or apps/ with an
# .expected holding a digit, a `PASS` assertion line, or a line that is not a literal
# in its own source (L-NAMED: a fixed OK line computes nothing; "and-mid=yes" built
# by an if does), and no .skip. A test a .ps1 harness drives with no .expected
# beside it is invisible here. A generated chapter whose header reads "Generated by
# <tool> ... from X.codex" reaches X.codex beside it: a test of the PTX that
# codex/plugs/ptx/run.ps1 -Chapter emits is a test of the [Device] source, true only
# while the generated chapter is regenerated after every source change. A chapter that names a
# codex/compiler/Core/CdxCodes.codex constant whose code a .failing or .diag sidecar under
# codex/test pins (its chapter present, no .skip) is reached: the compiler test raised that
# code. The sidecar pins the code, not the raiser, so every chapter naming the constant is
# credited; its cite closure is not, because opening.codex names constants and cites the
# whole compiler.
# A cite of a quire registered in build/host/windows/quire-map.ps1 resolves to
# <quire dir>/<chapter>, and a cite of a manifest quire (Codex, Emit, Semantics)
# to every file its manifest names but the entry chapter, as the compile resolves
# them; any other cite resolves by
# chapter name, and a name two chapters share outside a registered quire
# directory is reported and not graded. A chapter declaring `opening` is a program, which nothing can
# cite (L-UNCITABLE), so programs are counted apart: one with an .expected is a
# test, one under an app whose tests/ holds a .uiscript is GUI-driven, and the
# rest are run by no test. A chapter with no definition, operation or type (an
# effect that declares no operation) has nothing to compute and is counted apart
# as declarations only. The closure over-credits (a cite is not a call) and
# that is the direction to read it in: an unreached chapter is certainly
# untested, a reached one only possibly tested.
#
# -Diagnostics: every code registered in codex/compiler/Core/CdxCodes.codex
# against the codes named by .failing and .diag sidecars under codex/test, then
# the rows of build/guard-sabotage.ps1, which grades a guard no valid program
# reaches by patching a scratch compiler; no gate runs it. Any other script that
# greps for a code is not a grade.
[CmdletBinding()]
param(
    [string]$Tree = '',
    [switch]$List,
    [switch]$Diagnostics
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path

if ($Diagnostics) {
    $reg = Get-Content (Join-Path $Root 'codex/compiler/Core/CdxCodes.codex')
    $const = @{}
    foreach ($l in $reg) { if ($l -match '^\s+(cdx-[a-z0-9-]+) : Integer = (\d+)\s*$') { $const[$Matches[1]] = [int]$Matches[2] } }
    $pinned = @{}
    $side = @(Get-ChildItem (Join-Path $Root 'codex/test') -Recurse -File -Include *.failing, *.diag)
    foreach ($f in $side) {
        foreach ($l in Get-Content $f.FullName) {
            foreach ($m in [regex]::Matches($l, '^\s*(?:CDX)?0*([0-9]{1,4})(?:@\d+:\d+)?\s*$')) { $pinned[[int]$m.Groups[1].Value] = $true }
        }
    }
    $unpinnable = @{
        9012 = 'codegen backstop: the type checker refuses ordering on Text first, CDX2089'
        9016 = 'raised only on the IR-emit path (emit-ir-uni, mode flag fidelity); every runner compiles CDX'
    }
    $sabotage = @{}
    foreach ($l in Get-Content (Join-Path $Root 'build/guard-sabotage.ps1')) { if ($l -match "^\s*@\{ code = '(\d+)';") { $sabotage[[int]$Matches[1]] = $true } }
    $rows = @($const.Keys | ForEach-Object { [pscustomobject]@{ code = $const[$_]; name = $_; pinned = $pinned.ContainsKey($const[$_]) } } | Sort-Object code)
    $loose = @($rows | Where-Object { -not $_.pinned })
    $bySabotage = @($loose | Where-Object { $sabotage.ContainsKey($_.code) })
    $open = @($loose | Where-Object { -not $sabotage.ContainsKey($_.code) -and -not $unpinnable.ContainsKey($_.code) })
    $cannot = @($loose | Where-Object { -not $sabotage.ContainsKey($_.code) -and $unpinnable.ContainsKey($_.code) })
    Write-Host "registered: $($rows.Count); sidecars read: $($side.Count); pinned: $(@($rows | Where-Object pinned).Count); graded only by build/guard-sabotage.ps1 ($($sabotage.Count) rows, run by hand): $($bySabotage.Count); ungraded: $($open.Count); unpinnable by a sidecar: $($cannot.Count)"
    foreach ($r in $open) { Write-Host ("  {0,5} {1}" -f $r.code, $r.name) }
    foreach ($r in $cannot) { Write-Host ("  {0,5} {1}  (unpinnable: {2})" -f $r.code, $r.name, $unpinnable[$r.code]) }
    foreach ($r in $bySabotage) { Write-Host ("  {0,5} {1}  (sabotage)" -f $r.code, $r.name) }
    exit 0
}

if (-not $Tree) { Write-Host 'FAIL: name -Tree <dir> or -Diagnostics'; exit 1 }
$treeRel = ($Tree -replace '\\', '/').TrimEnd('/')
if (-not (Test-Path -PathType Container (Join-Path $Root $treeRel))) { Write-Host "FAIL: $treeRel is not a directory"; exit 1 }

function Key([string]$s) { ($s -replace '\s', '').ToLowerInvariant() }

. (Join-Path $Root 'build/host/windows/quire-map.ps1')
$quireDir = @{}
foreach ($q in $QuireDirs.Keys) { $quireDir[$q.ToLowerInvariant()] = ($QuireDirs[$q] -replace '\\', '/').ToLowerInvariant() }
$dirQuired = @{}
foreach ($d in $quireDir.Values) { $dirQuired[$d] = $true }
$manifestUnit = @{}; $inManifest = @{}
foreach ($q in $QuireManifests.Keys) {
    $rows = @(Get-Content (Join-Path $Root $QuireManifests[$q]) | ForEach-Object { $_.Trim() } | Where-Object { $_ -and -not $_.StartsWith('#') } | ForEach-Object { $_ -replace '\\', '/' })
    $manifestUnit[$q.ToLowerInvariant()] = $rows
    foreach ($r in $rows) { $inManifest[$r.ToLowerInvariant()] = $true }
}

$nodes = @{}; $byName = @{}; $shared = @{}; $byDirKey = @{}
$files = @(Get-ChildItem (Join-Path $Root 'codex'), (Join-Path $Root 'apps') -Recurse -Filter *.codex |
    Where-Object { $_.FullName -notmatch '[\\/]build-output[\\/]' })
foreach ($f in $files) {
    $rel = $f.FullName.Substring($Root.Length + 1) -replace '\\', '/'
    $text = Get-Content $f.FullName
    $head = $text | Where-Object { $_ -match '^Chapter:\s*(.+?)\s*$' } | Select-Object -First 1
    if (-not ($head -and $head -match '^Chapter:\s*(.+?)\s*$')) { continue }
    $k = Key $Matches[1]
    $cites = @($text | Where-Object { $_ -match '^\s+cites ([A-Za-z]+) chapter ([A-Za-z0-9 \-]+?)\s*(\(|$)' } | ForEach-Object { $Matches[1].ToLowerInvariant() + '|' + (Key $Matches[2]) })
    $from = $null
    $gen = $text | Where-Object { $_ -match '^\s+Generated by \S+ .*\bfrom ([A-Za-z0-9]+\.codex)\b' } | Select-Object -First 1
    if ($gen -and $gen -match '\bfrom ([A-Za-z0-9]+\.codex)\b') {
        $src = Join-Path $f.DirectoryName $Matches[1]
        if (Test-Path $src) { $from = $src.Substring($Root.Length + 1) -replace '\\', '/' }
    }
    $cdxRefs = @([regex]::Matches(($text -join "`n"), '\bcdx-[a-z0-9-]+\b') | ForEach-Object { $_.Value } | Sort-Object -Unique)
    $base = $f.FullName -replace '\.codex$', ''
    $test = $false
    if ((Test-Path "$base.expected") -and -not (Test-Path "$base.skip")) {
        $exp = Get-Content "$base.expected" -Raw
        if ($exp -and $exp -cmatch '[0-9]|PASS') { $test = $true }
        elseif ($exp) {
            $srcText = $text -join "`n"
            $test = @(($exp -split "`r?`n") | Where-Object { $_.Trim() -and -not $srcText.Contains($_) }).Count -gt 0
        }
    }
    $entry = [bool]($text | Where-Object { $_ -match '^\s+opening\s*(:|=)' } | Select-Object -First 1)
    $empty = -not ($text | Where-Object { $_ -match '^\s+[a-z][A-Za-z0-9\-]*\s*(:|\()' -or $_ -match '^\s+[A-Z][A-Za-z0-9]*\s*=' } | Select-Object -First 1)
    $nodes[$rel] = [pscustomobject]@{ rel = $rel; key = $k; cites = $cites; from = $from; cdx = $cdxRefs; test = $test; entry = $entry; empty = $empty; reached = $false; gui = $false }
    if ($byName.ContainsKey($k)) { $shared[$k] = $true } else { $byName[$k] = $rel }
    $dir = ($rel.Substring(0, $rel.LastIndexOf('/'))).ToLowerInvariant()
    if ($dirQuired.ContainsKey($dir)) { $byDirKey["$dir|$k"] = $rel; $byDirKey["$dir|$(Key $f.BaseName)"] = $rel }
}

# A cite of a registered directory quire resolves to the chapter in that quire's
# directory, as build/host/windows/quire-map.ps1 resolves it for every compile, so
# a name two quires share is graded per quire. Any other cite resolves by name.
function Resolve-Cite([string]$c) {
    $q, $k = $c -split '\|', 2
    if ($manifestUnit.ContainsKey($q)) { return @($manifestUnit[$q] | Where-Object { $nodes.ContainsKey($_) -and -not $nodes[$_].entry }) }
    if ($quireDir.ContainsKey($q)) { $hit = $byDirKey["$($quireDir[$q])|$k"]; if ($hit) { return @($hit) } }
    if ($shared.ContainsKey($k)) { return @() }
    if ($byName.ContainsKey($k)) { return @($byName[$k]) }
    return @()
}
function Is-Exact($n) { $d = ($n.rel.Substring(0, $n.rel.LastIndexOf('/'))).ToLowerInvariant(); return $dirQuired.ContainsKey($d) -or $inManifest.ContainsKey($n.rel.ToLowerInvariant()) }

function Walk($start, [string]$mark) {
    $stack = New-Object System.Collections.Generic.Stack[string]
    $seen = @{}
    foreach ($c in $start.cites) { foreach ($r in (Resolve-Cite $c)) { $stack.Push($r) } }
    if ($start.from -and $nodes.ContainsKey($start.from)) { $stack.Push($start.from) }
    while ($stack.Count) {
        $r = $stack.Pop()
        if ($seen.ContainsKey($r)) { continue }
        $seen[$r] = $true
        $n = $nodes[$r]
        $n.$mark = $true
        foreach ($c in $n.cites) { foreach ($x in (Resolve-Cite $c)) { if (-not $seen.ContainsKey($x)) { $stack.Push($x) } } }
        if ($n.from -and $nodes.ContainsKey($n.from) -and -not $seen.ContainsKey($n.from)) { $stack.Push($n.from) }
    }
}

foreach ($t in @($nodes.Values | Where-Object test)) { Walk $t 'reached' }
$codeNames = @{}
foreach ($l in Get-Content (Join-Path $Root 'codex/compiler/Core/CdxCodes.codex')) {
    if ($l -match '^\s+(cdx-[a-z0-9-]+) : Integer = (\d+)\s*$') { $n = [int]$Matches[2]; if (-not $codeNames.ContainsKey($n)) { $codeNames[$n] = @() }; $codeNames[$n] += $Matches[1] }
}
$pinnedNames = @{}
foreach ($sc in Get-ChildItem (Join-Path $Root 'codex/test') -Recurse -File -Include *.failing, *.diag) {
    $stem = $sc.FullName -replace '\.(failing|diag)$', ''
    if (-not (Test-Path "$stem.codex") -or (Test-Path "$stem.skip")) { continue }
    foreach ($l in Get-Content $sc.FullName) {
        if ($l -match '^\s*(?:CDX)?0*([0-9]{1,4})(?:@\d+:\d+)?\s*$' -and $codeNames.ContainsKey([int]$Matches[1])) { foreach ($cn in $codeNames[[int]$Matches[1]]) { $pinnedNames[$cn] = $true } }
    }
}
foreach ($n in @($nodes.Values | Where-Object { $_.rel -ne 'codex/compiler/Core/CdxCodes.codex' -and -not $_.test -and @($_.cdx | Where-Object { $pinnedNames.ContainsKey($_) }).Count })) {
    $n.reached = $true
}
$guiApps = @{}
foreach ($d in Get-ChildItem (Join-Path $Root 'apps') -Directory) {
    if (Get-ChildItem (Join-Path $d.FullName 'tests') -Filter *.uiscript -ErrorAction SilentlyContinue | Select-Object -First 1) { $guiApps[$d.Name] = $true }
}
foreach ($p in @($nodes.Values | Where-Object { $_.entry -and $_.rel -match '^apps/([^/]+)/' -and $guiApps.ContainsKey($Matches[1]) })) { $p.gui = $true; Walk $p 'gui' }

$inTree = @($nodes.Values | Where-Object { $_.rel -like "$treeRel/*" })
$sharedHere = @($inTree | Where-Object { $shared.ContainsKey($_.key) -and -not (Is-Exact $_) })
$graded = @($inTree | Where-Object { -not ($shared.ContainsKey($_.key) -and -not (Is-Exact $_)) -and -not $_.test })
$programs = @($graded | Where-Object entry)
$declOnly = @($graded | Where-Object { -not $_.entry -and $_.empty })
$library = @($graded | Where-Object { -not $_.entry -and -not $_.empty })
$unreached = @($library | Where-Object { -not $_.reached })

Write-Host "census of $treeRel ($((Get-Date).ToString('yyyy-MM-dd'))): $($inTree.Count) chapters"
Write-Host "  tests (.expected with a digit or a PASS line): $(@($inTree | Where-Object test).Count)"
Write-Host "  shared names, not graded: $($sharedHere.Count)"
Write-Host "  programs without an .expected: $($programs.Count) ($(@($programs | Where-Object gui).Count) GUI-driven)"
Write-Host "  declarations only (no definition, operation or type to compute): $($declOnly.Count)"
Write-Host "  library chapters: $($library.Count); reached by a computing test: $($library.Count - $unreached.Count); reached only by a GUI-driven program: $(@($unreached | Where-Object gui).Count); reached by nothing: $(@($unreached | Where-Object { -not $_.gui }).Count)"
$depth = ($treeRel -split '/').Count
$rowsOut = $library | Group-Object { $p = $_.rel -split '/'; if ($p.Count -gt $depth + 1) { $p[$depth] } else { '.' } } | ForEach-Object {
    $g = $_.Group
    [pscustomobject]@{ area = $_.Name; library = $g.Count; untested = @($g | Where-Object { -not $_.reached }).Count; nothing = @($g | Where-Object { -not $_.reached -and -not $_.gui }).Count }
} | Sort-Object untested -Descending
$rowsOut | Format-Table -AutoSize | Out-String -Width 160 | Write-Host
if ($List) {
    foreach ($u in ($unreached | Sort-Object rel)) { Write-Host ("  {0}{1}" -f $u.rel, $(if ($u.gui) { '  (GUI-driven only)' } else { '' })) }
    foreach ($p in ($programs | Sort-Object rel)) { Write-Host ("  {0}  (program, no .expected{1})" -f $p.rel, $(if ($p.gui) { '; GUI-driven' } else { '' })) }
    foreach ($e in ($declOnly | Sort-Object rel)) { Write-Host ("  {0}  (declarations only)" -f $e.rel) }
}
exit 0
