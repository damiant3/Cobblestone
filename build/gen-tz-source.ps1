# gen-tz-source.ps1 -- write codex/foreword/core/TzSource.codex from a vendored
# IANA tzdata release.
#
# The ten rule files under codex/foreword/core/tzdata/<release>/ are checked
# against MANIFEST.txt; any mismatch, missing file, backslash or double quote
# refuses. Comments are cut at '#', tabs become spaces, trailing blanks and
# empty lines are dropped, and each file becomes one Text literal in parse
# order. TzRules.codex parses the result.
#
#   pwsh build/gen-tz-source.ps1 -Release 2026f [-Check]
#
# -Check writes nothing and exits 1 when the chapter on disk differs from what
# the release would generate.
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Release,
    [switch]$Check
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$dir = Join-Path $repo "codex/foreword/core/tzdata/$Release"
$out = Join-Path $repo 'codex/foreword/core/TzSource.codex'
$names = @('africa', 'antarctica', 'asia', 'australasia', 'europe', 'northamerica', 'southamerica', 'etcetera', 'backward', 'factory')

$manifest = @{}
foreach ($line in (Get-Content -LiteralPath (Join-Path $dir 'MANIFEST.txt'))) {
    if ($line -match '^([0-9A-F]{64})  (\S+)$') { $manifest[$Matches[2]] = $Matches[1] }
}
$nl = "`r`n"
$sb = [System.Text.StringBuilder]::new()
[void]$sb.Append("Chapter: TzSource$nl$nl Generated by build/gen-tz-source.ps1 from the IANA tzdata release$nl named below. Do not edit; regenerate.$nl${nl}Section: Release$nl$nl  tz-release : Text$nl  tz-release = `"$Release`"$nl${nl}Section: Rule Text$nl")
foreach ($n in $names) {
    $path = Join-Path $dir $n
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "missing $n in $dir" }
    $hash = (Get-FileHash -LiteralPath $path).Hash
    if (-not $manifest.ContainsKey($n) -or $manifest[$n] -ne $hash) { throw "$n does not match MANIFEST.txt" }
    $kept = foreach ($l in (Get-Content -LiteralPath $path)) {
        $s = (($l -replace '#.*$', '') -replace "`t", ' ').TrimEnd()
        if ($s.Trim()) { $s }
    }
    $body = $kept -join '\n'
    if ($body.Contains('\\') -or $body.Contains('"')) { throw "$n carries a backslash or a quote" }
    [void]$sb.Append("$nl  tz-src-$n : Text$nl  tz-src-$n = `"$body\n`"$nl")
}
[void]$sb.Append("${nl}Section: Sources$nl$nl  tz-sources : List Text$nl  tz-sources = [" + (($names | ForEach-Object { "tz-src-$_" }) -join ', ') + "]$nl")
$text = $sb.ToString()
if ($Check) {
    $cur = if (Test-Path -LiteralPath $out) { [System.IO.File]::ReadAllText($out) } else { '' }
    if ($cur -ne $text) { Write-Host "TzSource.codex differs from release $Release"; exit 1 }
    Write-Host "TzSource.codex matches release $Release"; exit 0
}
[System.IO.File]::WriteAllText($out, $text, [System.Text.UTF8Encoding]::new($false))
Write-Host "wrote $out ($((Get-Item -LiteralPath $out).Length) bytes) from release $Release"
