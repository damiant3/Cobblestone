# flux-oracle.py -- one Flux transformer call through Diffusion Forge's own
# IntegratedFluxTransformer2DModel, written out as the Codex chapter the
# guest's Flux transformer is graded against.
#
#   D:\AI\DiffusionForge\system\python\python.exe build/flux-oracle.py <checkpoint> <out.codex> [<sampler out.codex>]
#
# The config is Forge's own detect_unet_config over the checkpoint's keys. The
# model is built on the meta device and called through Forge's own forward;
# each top-level module (img_in, time_in, vector_in, txt_in, every double and
# single block, final_layer) is given its weights from the checkpoint, each
# e4m3 value widened to float32 exactly, just before it runs and freed after,
# so the device holds one block and not the 48 GB of f32 weights. The inputs
# are the formulas below, which the guest repeats; each is a multiple of 1/256,
# exact in f16. Every module output (a double block's img and txt apart) and
# the unpatchified result are recorded as shape, mean, root mean square and the
# values at SAMPLES positions (j * STRIDE + OFFSET) mod numel.
import inspect, math, os, sys
import numpy as np
import torch

WEBUI = r'D:\AI\DiffusionForge\webui'
sys.path.insert(0, WEBUI)
sys.path.insert(0, os.path.join(WEBUI, 'repositories', 'huggingface_guess'))
sys.path.insert(0, os.path.join(WEBUI, 'packages_3rdparty'))

H = W = 16
TXT = 32
SIGMA = 0.75
SAMPLES, STRIDE, OFFSET = 64, 7919, 13

def latent(i): return ((i * 37 + 11) % 257 - 128) / 128.0
def context(i): return ((i * 13 + 5) % 251 - 125) / 256.0
def pooled(i): return ((i * 29 + 3) % 241 - 120) / 256.0

def real(v):
    s = np.format_float_positional(np.float32(v), unique=True, trim='0')
    if s.endswith('.'): s += '0'
    return '(0.0 - ' + s[1:] + ')' if s.startswith('-') else s

def main():
    global sys_args
    sys_args = list(sys.argv)
    ckpt, out = sys.argv[1], sys.argv[2]
    sys.argv = sys.argv[:1]
    from safetensors import safe_open
    from huggingface_guess import detection
    from backend.nn.flux import IntegratedFluxTransformer2DModel

    f = safe_open(ckpt, framework='pt')
    keys = list(f.keys())
    cfg = detection.detect_unet_config({k: torch.empty(f.get_slice(k).get_shape(), device='meta') for k in keys}, '')
    accepted = inspect.signature(IntegratedFluxTransformer2DModel.__init__).parameters
    for k in [k for k in cfg if k not in accepted]:
        del cfg[k]
    with torch.device('meta'):
        model = IntegratedFluxTransformer2DModel(**cfg).float().eval()
    names = set(model.state_dict())
    if names != set(keys):
        print('REFUSE: %d model tensors not in the checkpoint, %d checkpoint tensors not in the model' % (len(names - set(keys)), len(set(keys) - names)))
        sys.exit(1)

    records = []
    def attach(mod, prefix, label):
        def pre(m, a):
            m.to_empty(device='cuda')
            with torch.no_grad():
                for k, p in m.state_dict().items():
                    p.copy_(f.get_tensor(prefix + k).to('cuda').float())
        def post(m, a, o):
            if isinstance(o, tuple):
                records.append((label + ' img', o[0].detach().float().cpu()))
                records.append((label + ' txt', o[1].detach().float().cpu()))
            else:
                records.append((label, o.detach().float().cpu()))
            m.to('meta')
            torch.cuda.empty_cache()
        mod.register_forward_pre_hook(pre)
        mod.register_forward_hook(post)
    for n in ['img_in', 'time_in', 'vector_in', 'txt_in']:
        attach(getattr(model, n), n + '.', n)
    for i, m in enumerate(model.double_blocks): attach(m, 'double_blocks.%d.' % i, 'double %d' % i)
    for i, m in enumerate(model.single_blocks): attach(m, 'single_blocks.%d.' % i, 'single %d' % i)
    attach(model.final_layer, 'final_layer.', 'final')

    x = torch.tensor([latent(i) for i in range(16 * H * W)], dtype=torch.float32).reshape(1, 16, H, W).cuda()
    ctx = torch.tensor([context(i) for i in range(TXT * 4096)], dtype=torch.float32).reshape(1, TXT, 4096).cuda()
    y = torch.tensor([pooled(i) for i in range(768)], dtype=torch.float32).reshape(1, 768).cuda()
    with torch.no_grad():
        o = model(x, torch.tensor([SIGMA]).cuda(), ctx, y)
    records.append(('out', o.detach().float().cpu()))

    lines = ['Chapter: FluxReference', '',
             ' Generated by build/flux-oracle.py from %s: one Flux' % os.path.basename(ckpt),
             ' transformer call through Diffusion Forge\'s own model in float32.', ' Regenerate, do not edit.', '',
             ' We say:', '', 'Section: Blocks', '',
             '  FluxRefBlock = record {', '    frb-name : Text,', '    frb-count : Integer,',
             '    frb-mean : Real,', '    frb-rms : Real,', '    frb-samples : List Real', '  }', '',
             '  flux-ref-h : Integer = %d' % H, '', '  flux-ref-w : Integer = %d' % W, '',
             '  flux-ref-txt : Integer = %d' % TXT, '', '  flux-ref-sigma : Real = %s' % real(SIGMA), '',
             '  flux-ref-samples : Integer = %d' % SAMPLES, '', '  flux-ref-stride : Integer = %d' % STRIDE, '',
             '  flux-ref-offset : Integer = %d' % OFFSET, '']
    refs = []
    for k, (name, t) in enumerate(records):
        v = t.reshape(-1).numpy().astype(np.float64)
        n = v.size
        s = ', '.join(real(v[(j * STRIDE + OFFSET) % n]) for j in range(SAMPLES))
        d = 'flux-ref-%d' % k
        refs.append(d)
        lines += ['  %s : FluxRefBlock' % d,
                  '  %s = FluxRefBlock { frb-name = "%s", frb-count = %d, frb-mean = %s, frb-rms = %s, frb-samples = [%s] }'
                  % (d, name, n, real(v.mean()), real(math.sqrt((v * v).mean())), s), '']
    lines += ['  flux-ref-blocks : List FluxRefBlock', '  flux-ref-blocks = [%s]' % ', '.join(refs), '', 'Page 1', '']
    open(out, 'w', newline='\r\n').write('\n'.join(lines))
    print('%d records, config %s' % (len(records), cfg))
    if len(sys_args) > 3:
        euler(model, ctx, y, sys_args[3])

# The sampler reference: k-diffusion's own sample_euler (webui/k_diffusion) over
# Forge's PredictionFlux as its schnell engine builds it (mu = 1), the model
# wrapped as Forge's KModel wraps it (calculate_input, timestep,
# calculate_denoised), EULER_STEPS sigmas from Forge's own simple_scheduler
# over the predictor's table, the start its noise_scaling of noise(i) over a
# zero latent. Every sigma, and each step's output latent, is recorded.
EULER_STEPS = 4
def noise(i): return ((i * 53 + 17) % 263 - 131) / 128.0

def euler(model, ctx, y, out):
    from k_diffusion import sampling
    from backend.modules.k_prediction import PredictionFlux
    from modules.sd_schedulers import simple_scheduler
    pred = PredictionFlux(mu=1.0)
    sigmas = simple_scheduler(EULER_STEPS, float(pred.sigma_min), float(pred.sigma_max), pred, 'cuda')
    class Den(torch.nn.Module):
        def forward(self, x, sigma, **kw):
            o = model(pred.calculate_input(sigma, x), pred.timestep(sigma), ctx, y)
            return pred.calculate_denoised(sigma, o, x)
    den = Den()
    nz = torch.tensor([noise(i) for i in range(16 * H * W)], dtype=torch.float32).reshape(1, 16, H, W).cuda()
    x = pred.noise_scaling(sigmas[0].reshape(1, 1, 1, 1), nz, torch.zeros_like(nz))
    xs = []
    with torch.no_grad():
        for i in range(EULER_STEPS):
            x = sampling.sample_euler(den, x, sigmas[i:i + 2], disable=True)
            xs.append(x.detach().float().cpu())
    lines = ['Chapter: FluxSamplerReference', '',
             ' Generated by build/flux-oracle.py: k-diffusion sample_euler over Forge\'s', ' PredictionFlux and Flux model, simple schedule. Regenerate, do not edit.', '',
             ' We say:', '', 'Section: Steps', '',
             '  FluxRefStep = record {', '    frs-rms : Real,', '    frs-samples : List Real', '  }', '',
             '  flux-sampler-ref-sigmas : List Real', '  flux-sampler-ref-sigmas = [%s]' % ', '.join(real(float(s)) for s in sigmas), '']
    names = []
    for k, xt in enumerate(xs):
        v = xt.reshape(-1).numpy().astype(np.float64)
        n = v.size
        s = ', '.join(real(v[(j * STRIDE + OFFSET) % n]) for j in range(SAMPLES))
        names.append('flux-sampler-ref-%d' % k)
        lines += ['  flux-sampler-ref-%d : FluxRefStep' % k,
                  '  flux-sampler-ref-%d = FluxRefStep { frs-rms = %s, frs-samples = [%s] }' % (k, real(math.sqrt((v * v).mean())), s), '']
    lines += ['  flux-sampler-ref-steps : List FluxRefStep', '  flux-sampler-ref-steps = [%s]' % ', '.join(names), '', 'Page 1', '']
    open(out, 'w', newline='\r\n').write('\n'.join(lines))
    print('%d Euler steps, sigmas %s' % (EULER_STEPS, [float(s) for s in sigmas]))

main()
