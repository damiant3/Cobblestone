# Print the meta-block header fields OUR reader computes, so they can be compared
# against the values a host-side RFC parser reads off the same bytes.
#
#   pwsh build/brotli-hdr-probe.ps1 -Case cyclic
#
# This exists because a refusal says only "somewhere before the first command".
# The header is a dozen fields read in a fixed order and any one of them being
# wrong desynchronises every field after it, so the useful question is WHICH,
# and that is one boot away rather than a reasoning exercise.

param(
  [string]$Case = "cyclic",
  [string]$Kernel = "seed/Codex.cdx",
  [int]$TimeoutSec = 120
)

$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$outAbs = Join-Path $root "test-output/brotli-read"
New-Item -ItemType Directory -Force $outAbs | Out-Null
$kernelPath = if ([IO.Path]::IsPathRooted($Kernel)) { $Kernel } else { Join-Path $root $Kernel }

function New-Cyclic([int]$n) {
  $pat = @(65,66,65,67,65,66,68,65); $out = New-Object byte[] $n
  for ($i = 0; $i -lt $n; $i++) { $out[$i] = [byte]$pat[$i % 8] }
  return $out
}
function New-Mixed([int]$n) {
  $out = [System.Collections.Generic.List[byte]]::new(); $s = 7
  while ($out.Count -lt $n) {
    $s = (($s * 1103515245 + 12345) -band 2147483647)
    if (($s % 3) -eq 0) { for ($j = 0; $j -lt 40; $j++) { $out.Add([byte](97 + (($s + $j) % 26))) } }
    else {
      $take = [math]::Min(60, $out.Count)
      if ($take -gt 0) { $from = $out.Count - $take
        foreach ($b in $out.GetRange($from, $take).ToArray()) { $out.Add($b) } }
      else { for ($j = 0; $j -lt 40; $j++) { $out.Add([byte](32 + ($j % 90))) } }
    }
  }
  return $out.ToArray()[0..($n - 1)]
}

function New-Prose([int]$n) {
  $w = @("the","quick","brown","fox","jumps","over","lazy","dog",
         "and","then","runs","far","away","into","the","woods")
  $out = [System.Collections.Generic.List[byte]]::new(); $s = 4242
  while ($out.Count -lt $n) {
    $s = (($s * 1103515245 + 12345) -band 2147483647)
    $k = [math]::Floor($s / 4096) % 16
    $sep = if ([math]::Floor($s / 256) % 16 -eq 0) { ". " } else { " " }
    foreach ($b in [Text.Encoding]::UTF8.GetBytes($w[$k] + $sep)) { $out.Add($b) }
  }
  return $out.ToArray()
}

$data = switch ($Case) {
  "cyclic" { New-Cyclic 4000 }
  "mixed"  { New-Mixed 6000 }
  "prose"  { New-Prose 8000 }
  default  { throw "case $Case not wired into this probe" }
}

$ms = [IO.MemoryStream]::new()
$bs = [IO.Compression.BrotliStream]::new($ms, [IO.Compression.CompressionLevel]::SmallestSize)
$bs.Write($data, 0, $data.Length); $bs.Dispose()
$comp = $ms.ToArray()
$blist = ($comp | ForEach-Object { [int]$_ }) -join ", "

$L = @()
$L += "Chapter: BrotliHdrProbe"
$L += "  cites Compress chapter Brotli"
$L += ""
$L += " GENERATED by build/brotli-hdr-probe.ps1. Do not edit by hand."
$L += ""
$L += " Walks the meta-block header in the order brotli-compressed walks it and"
$L += " prints every field, so a divergence can be located instead of guessed at."
$L += ""
$L += "Section: Body"
$L += ""
$L += "  hp-in : List Integer = [$blist]"
$L += ""
$L += "  hp-join : List Integer, Integer, Integer, Text -> Text"
$L += "  hp-join (xs) (i) (n) (acc) ="
$L += "    if i >= n then acc"
$L += "    else hp-join xs (i + 1) n (acc & show (list-at xs i) & `" `")"
$L += ""
$L += "  opening : [Console] Nothing"
$L += "  opening = act"
$L += "    let r0 = BitReader { br-bytes = hp-in, br-pos = 0 }"
$L += "    in let wv = brotli-read-wbits r0"
$L += "    in let r1 = wv.bw2-r"
$L += "    in let islast = br-bit r1"
$L += "    in let r2 = br-advance r1 1"
$L += "    in let r3 = if islast == 1 then br-advance r2 1 else r2"
$L += "    in let sel = br-bits r3 2"
$L += "    in let nb = (4 + sel) * 4"
$L += "    in let mlen = br-bits (br-advance r3 2) nb + 1"
$L += "    in let r4 = br-advance (br-advance r3 2) nb"
$L += "    in let r5 = if islast == 1 then r4 else br-advance r4 1"
$L += "    in let nbl = brotli-varlen-read r5"
$L += "    in let bi = brotli-read-split (nbl.bv-r)"
$L += "    in let bd = brotli-read-split (bi.bz-r)"
$L += "    in let npostfix = br-bits (bd.bz-r) 2"
$L += "    in let ndirect = bit-shl (br-bits (br-advance (bd.bz-r) 2) 4) npostfix"
$L += "    in let cmode = br-bits (br-advance (bd.bz-r) 6) 2"
$L += "    in let nl = brotli-varlen-read (br-advance (bd.bz-r) (6 + 2 * (nbl.bv-v)))"
$L += "    in let mp = brotli-read-cmap (nl.bv-r) (nl.bv-v) (brotli-ctx-count * (nbl.bv-v))"
$L += "    in let nd = brotli-varlen-read (mp.bm-r)"
$L += "    in let dmp = brotli-read-cmap (nd.bv-r) (nd.bv-v) ((bd.bz-n) * 4)"
$L += "    in let ts = brotli-read-decs (dmp.bm-r) (nl.bv-v) 256 8 0 []"
$L += "    in let iks = brotli-read-decs (ts.bs-r) (bi.bz-n) brotli-ic-alpha 10 0 []"
$L += "    in let dalpha = brotli-dist-alpha-of npostfix ndirect"
$L += "    in let dks = brotli-read-decs (iks.bs-r) (nd.bv-v) dalpha (brotli-abits-of dalpha) 0 []"
$L += "    in let s = brotli-get-sym (dks.bs-r) (list-at (iks.bs-list) 0)"
$L += "    in let insc = brotli-ic-ins-code (s.dr-sym)"
$L += "    in let cpyc = brotli-ic-cpy-code (s.dr-sym)"
$L += "    in let ins = list-at brotli-ins-base insc + br-bits (s.dr-reader) (list-at brotli-ins-extra insc)"
$L += "    in let r2 = br-advance (s.dr-reader) (list-at brotli-ins-extra insc)"
$L += "    in let cpy = list-at brotli-cpy-base cpyc + br-bits r2 (list-at brotli-cpy-extra cpyc)"
$L += "    in act"
$L += "      print-line-uni (`"wbits `" & show (wv.bw2-wbits))"
$L += "      print-line-uni (`"islast `" & show islast)"
$L += "      print-line-uni (`"mlen `" & show mlen)"
$L += "      print-line-uni (`"nbltypesl `" & show (nbl.bv-v))"
$L += "      print-line-uni (`"nbltypesi `" & show (bi.bz-n))"
$L += "      print-line-uni (`"nbltypesd `" & show (bd.bz-n))"
$L += "      print-line-uni (`"npostfix `" & show npostfix)"
$L += "      print-line-uni (`"ndirect `" & show ndirect)"
$L += "      print-line-uni (`"cmode `" & show cmode)"
$L += "      print-line-uni (`"ntreesl `" & show (nl.bv-v))"
$L += "      print-line-uni (`"ntreesd `" & show (nd.bv-v))"
$L += "      print-line-uni (`"dalpha `" & show dalpha)"
$L += "      print-line-uni (`"abits `" & show (brotli-abits-of dalpha))"
$L += "      print-line-uni (`"icsym `" & show (s.dr-sym))"
$L += "      print-line-uni (`"ins `" & show ins)"
$L += "      print-line-uni (`"cpy `" & show cpy)"
$L += "      print-line-uni (`"blen-i `" & show (bi.bz-blen))"
$L += "      print-line-uni (`"blen-d `" & show (bd.bz-blen))"
$L += "      print-line-uni (`"cmapl-n `" & show (list-length (mp.bm-map)))"
$L += "      print-line-uni (`"cmapd `" & hp-join (dmp.bm-map) 0 (list-length (dmp.bm-map)) `"`")"
$L += "    end"
$L += "  end"

$src = Join-Path $outAbs "hdr-$Case.codex"
[IO.File]::WriteAllLines($src, $L)
$cdx = Join-Path $outAbs "hdr-$Case.cdx"
$log = Join-Path $outAbs "hdr-$Case.log"
$vmo = Join-Path $outAbs "hdr-$Case.out"

Write-Host "[hdr-probe] $Case orig=$($data.Length)B net=$($comp.Length)B compiling ..."
Remove-Item $cdx -ErrorAction SilentlyContinue
& pwsh (Join-Path $root "build/compile.ps1") -Src $src -Out $cdx -Log $log -Kernel $kernelPath *>$null
if (-not (Test-Path $cdx)) {
  Write-Host "FAIL_COMPILE -- see $log" -ForegroundColor Red
  Select-String -Path $log -Pattern 'error CDX|CODEGEN-HALTED' | Select-Object -First 10 | ForEach-Object { $_.Line.Trim() }
  exit 1
}
Remove-Item $vmo -ErrorAction SilentlyContinue
$vm = Start-Process -FilePath (Join-Path $root "tools/codex-vm.exe") `
      -ArgumentList @("-kernel", $cdx, "-headless", "-output", $vmo, "-mem", "3072") `
      -PassThru -WindowStyle Hidden -RedirectStandardOutput (Join-Path $outAbs "vm-hdr-$Case.txt")
if (-not $vm.WaitForExit($TimeoutSec * 1000)) { try { $vm.Kill() } catch { }; Write-Host "TIMEOUT" -ForegroundColor Red; exit 1 }

Write-Host "--- OUR reader ---"
((Get-Content $vmo -Raw) -replace "`r", '' -replace "`0", '').Trim()
