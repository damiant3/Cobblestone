# Ratchet the warnings the compiler raises on its own source.
#
# COMPILER-16: the compiler's own warnings are gated by nobody. The CDX2064
# that opened that row was a live miscompilation the checker reported
# correctly on every build for as long as it existed, and nobody read it,
# which is L-BODY: gated only by a human noticing is not gated.
#
# A ratchet rather than a pin, because a warning cannot be pinned in this
# tree at all: codex/test/errors holds no .expected files and nothing under
# codex/test names a warning.
#
# Usage:
#   check-compiler-warnings.ps1 -Log <self-compile log>   # verdict
#   check-compiler-warnings.ps1 -Log <log> -Update        # rewrite the baseline
#   check-compiler-warnings.ps1 -Log <log> -List          # counts, no verdict
#
# The log is the one compile.ps1 writes for a self-compile, so produce it the
# way the seed chain already does and hand the same path to this:
#
#   build/concat-codex-self.ps1 -OutFile <unit>
#   build/compile.ps1 -Src <unit> -Out <cdx> -Log <log> -Repl -Kernel seed\Codex.cdx
#   build/check-compiler-warnings.ps1 -Log <log>
#
# WHICH LOG YOU HAND IT DECIDES WHAT IT MEASURES, and the wrong one reads
# exactly like the right one. A stage-2 log is the SEED compiling your source,
# so it reports the warnings the shipping compiler raises and says nothing
# about a checker change in your tree; the stage-3 log is your candidate
# compiling that same source and is the one that grades your change. Measured
# 2026-09-08 (red, COMPILER-71): the stage-2 census was read first and would
# have been published as evidence about a change it cannot see.
#
# IT BOOTS NOTHING. It reads a log that a compile you already ran produced.
#
# Exit 1 when any code's count RISES, and exit 1 when a count FALLS without
# the baseline being lowered in the same changelist. Failing on an
# improvement is the mechanism, not a wart: a baseline left high after a fix
# lets the warning come straight back, which is a ratchet that does not
# ratchet. The fix for that failure is one command, -Update.
#
# It also fails on any ERROR in the log, and on a log it cannot read. A check
# that passes because its input is absent is not a check, and a missing log
# is the likeliest way this one would be silently defeated.
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Log,
    [switch]$Update,
    [switch]$List
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$Baseline = Join-Path $PSScriptRoot 'compiler-warning-baseline.txt'

if (-not (Test-Path -PathType Leaf $Log)) {
    Write-Host "REFUSED: no log at $Log"
    Write-Host 'This check grades a self-compile log. Produce one with compile.ps1 -Log <path> and pass that path.'
    exit 1
}

$lines = [System.IO.File]::ReadAllLines((Resolve-Path $Log).Path)

$counts = @{}
$errors = 0
foreach ($line in $lines) {
    foreach ($m in [regex]::Matches($line, 'warning (CDX\d+)')) {
        $code = $m.Groups[1].Value
        if ($counts.ContainsKey($code)) { $counts[$code] = $counts[$code] + 1 } else { $counts[$code] = 1 }
    }
    $errors += [regex]::Matches($line, 'error CDX\d+').Count
}

$total = 0
foreach ($v in $counts.Values) { $total += $v }

if ($List) {
    foreach ($code in ($counts.Keys | Sort-Object)) {
        Write-Host ("  {0}  {1}" -f $counts[$code].ToString().PadLeft(5), $code)
    }
    Write-Host ("  {0}  total warnings, {1} errors" -f $total.ToString().PadLeft(5), $errors)
    exit 0
}

if ($Update) {
    $out = New-Object System.Collections.Generic.List[string]
    $out.Add('# compiler-warning-baseline.txt -- generated by build/check-compiler-warnings.ps1 -Update')
    $out.Add('#')
    $out.Add('# The warnings the compiler raises on its own source, one row per code as')
    $out.Add('#   <code> <count>')
    $out.Add('#')
    $out.Add('# A CEILING and a FLOOR at once: the check fails when a count rises, and')
    $out.Add('# fails when a count falls without this file being lowered in the same')
    $out.Add('# changelist. COMPILER-16 is the row that owns the number.')
    $out.Add('#')
    $out.Add(('# Measured {0}: {1} warnings, {2} errors.' -f (Get-Date -Format 'yyyy-MM-dd'), $total, $errors))
    $out.Add('')
    foreach ($code in ($counts.Keys | Sort-Object)) {
        $out.Add(("{0} {1}" -f $code, $counts[$code]))
    }
    Set-Content -Path $Baseline -Value $out -Encoding UTF8
    Write-Host ("check-compiler-warnings: baseline written, {0} warnings over {1} code(s)" -f $total, $counts.Count)
    exit 0
}

if (-not (Test-Path -PathType Leaf $Baseline)) {
    Write-Host "REFUSED: no baseline at $Baseline. Record one with -Update."
    exit 1
}

$want = @{}
foreach ($line in [System.IO.File]::ReadAllLines($Baseline)) {
    $t = $line.Trim()
    if ($t -eq '' -or $t.StartsWith('#')) { continue }
    $p = $t -split '\s+'
    if ($p.Count -ge 2) { $want[$p[0]] = [int]$p[1] }
}

$failed = $false

if ($errors -gt 0) {
    Write-Host "FAIL: the log carries $errors error(s). A self-compile that errors is not a warning question."
    $failed = $true
}

foreach ($code in (($counts.Keys + $want.Keys) | Sort-Object -Unique)) {
    $got = if ($counts.ContainsKey($code)) { $counts[$code] } else { 0 }
    $exp = if ($want.ContainsKey($code)) { $want[$code] } else { 0 }
    if ($got -gt $exp) {
        Write-Host ("FAIL: {0} rose {1} -> {2}" -f $code, $exp, $got)
        $failed = $true
    } elseif ($got -lt $exp) {
        Write-Host ("FAIL: {0} fell {1} -> {2} without the baseline being lowered. Run -Update in the changelist that fixed it." -f $code, $exp, $got)
        $failed = $true
    }
}

if ($failed) { exit 1 }

Write-Host ("check-compiler-warnings: OK ({0} warnings over {1} code(s), 0 errors)" -f $total, $counts.Count)
exit 0
