<#
.SYNOPSIS
  Writes apps/uoaix/Skill1998Data.codex from the 1998 server's skills.txt (draxinar/rundir).
.DESCRIPTION
  Per skill, in skills.txt order (the client's skill ids 0..45): the stat weights, SkillStat, StatAdvRate, CanUse,
  and the AdvRate curve B * A^x + C through (0, lower), (500, middle), (1000, higher) as integers: u = A^500 =
  (higher - middle) / (middle - lower), B = q^2 / (p - q), C = (lower (p - q) - q^2) / (p - q) with p = higher -
  middle, q = middle - lower, reduced, and A at the 2^30 fixed point by the bisection SmithModel uses (smm-root), so
  the server's curve and the modeler's agree to the bit.
.PARAMETER SkillsFile
  A local skills.txt. Omitted, the file is fetched from github.com/draxinar/rundir.
#>
param([string]$SkillsFile = '', [string]$OutFile = "$PSScriptRoot/Skill1998Data.codex")
$ErrorActionPreference = 'Stop'

$text = if ($SkillsFile) { Get-Content -Raw $SkillsFile } else {
  (Invoke-WebRequest -UseBasicParsing 'https://raw.githubusercontent.com/draxinar/rundir/main/skills.txt').Content }

function Field([string]$block, [string]$name) {
  if ($block -match "(?m)^\s*$name\s*:?\s+([^\r\n]+)") { return $Matches[1].Trim() }
  throw "skills.txt: no $name in block: $($block.Substring(0, [Math]::Min(60, $block.Length)))"
}
function Gcd([long]$a, [long]$b) { $a = [Math]::Abs($a); $b = [Math]::Abs($b); while ($b -ne 0) { $t = $a % $b; $a = $b; $b = $t }; return $a }

$one = [long]1073741824
function Mul([long]$a, [long]$b) { return [long](([System.Numerics.BigInteger]$a * $b) / $one) }
function Pow([long]$base, [long]$n, [long]$acc) {
  while ($n -ne 0) { if ($n % 2 -eq 1) { $acc = Mul $acc $base }; $base = Mul $base $base; $n = [long][Math]::Floor($n / 2) }
  return $acc
}
function Root([long]$p, [long]$q) {
  $lo = [long]0; $hi = $one; $target = [long](([System.Numerics.BigInteger]$p * $one) / $q)
  for ($left = 40; $left -gt 0; $left--) {
    $mid = [long][Math]::Floor(($lo + $hi) / 2)
    if ((Pow $mid 500 $one) -le $target) { $lo = $mid } else { $hi = $mid }
  }
  return $lo
}

$rows = @()
foreach ($block in ($text -split '#{10,}')) {
  if ($block -notmatch '(?m)^\s*Skill:\s*\S') { continue }
  $name = Field $block 'Skill'
  $adv = (Field $block 'AdvRate') -split '\s+' | ForEach-Object { [long]$_ }
  $l = $adv[0]; $m = $adv[1]; $h = $adv[2]
  $p = $h - $m; $q = $m - $l
  if ($q -eq 0 -or $p * $q -le 0 -or $p -eq $q) { throw "skills.txt ${name}: AdvRate $l $m $h has no decreasing exponential curve" }
  $bn = $q * $q; $den = $p - $q; $cn = $l * $den - $q * $q
  $g = Gcd $p $q; $p = $p / $g; $q = $q / $g
  if ($q -lt 0) { $p = -$p; $q = -$q }
  $g = Gcd (Gcd $bn $cn) $den; $bn /= $g; $cn /= $g; $den /= $g
  if ($den -lt 0) { $bn = -$bn; $cn = -$cn; $den = -$den }
  $rows += [pscustomobject]@{ Name = $name; Str = [int](Field $block 'Strength'); Dex = [int](Field $block 'Dexterity')
    Int = [int](Field $block 'Intelligence'); Stat = [int](Field $block 'SkillStat'); StatAdv = [int](Field $block 'StatAdvRate')
    Use = if ((Field $block 'CanUse') -match 'TRUE') { 1 } else { 0 }; Bn = $bn; Cn = $cn; Den = $den; Root = Root $p $q }
}
if ($rows.Count -ne 46) { throw "skills.txt: $($rows.Count) skills, expected the client's 46" }
foreach ($r in $rows) { if ($r.Str + $r.Dex + $r.Int -notin 0, 100) { throw "skills.txt $($r.Name): weights sum to $($r.Str + $r.Dex + $r.Int)" } }

function Line([string]$name, [string]$field) { "  $name : List Integer = [" + (($rows | ForEach-Object { if ($_.$field -lt 0) { "0 - $(-$_.$field)" } else { "$($_.$field)" } }) -join ', ') + "]" }
$out = @(
  'Chapter: Skill1998Data'
  ''
  ' Generated by import-skills1998.ps1 from the June 1998 server''s skills.txt (github.com/draxinar/rundir); do not edit.'
  ' Client skill id order. Weights in percent, SkillStat and StatAdvRate as written, CanUse 1 or 0. The AdvRate curve,'
  ' times 1000: (1000 * bn * A^s + 1000 * cn * 2^30) / (den * 2^30), A = root at the 2^30 fixed point.'
  ''
  (Line 's98d-str' 'Str'); (Line 's98d-dex' 'Dex'); (Line 's98d-int' 'Int'); (Line 's98d-skill-stat' 'Stat')
  (Line 's98d-stat-adv' 'StatAdv'); (Line 's98d-can-use' 'Use'); (Line 's98d-bn' 'Bn'); (Line 's98d-cn' 'Cn')
  (Line 's98d-den' 'Den'); (Line 's98d-root' 'Root')
  ''
  'Page 1'
)
[System.IO.File]::WriteAllText($OutFile, (($out -join "`r`n") + "`r`n"))
"wrote $OutFile ($($rows.Count) skills)"
