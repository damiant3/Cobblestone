param(
    [string]$ServUoRoot = 'D:/Projects/uo-reference/ServUO',
    [string]$Output = "$PSScriptRoot/DurabilityData.codex"
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# UOAIX-238: ServUO's starting durability per weapon and armour class (BaseWeapon and BaseArmor InitMinHits and
# InitMaxHits: a new item's hits and max hits are each a roll in that range). Every class under Scripts/Items/Equipment
# Weapons and Armor that declares both, keyed by the graphics its constructor (base(0x...)) and FlipableAttribute name.
# A graphic of the 1998 client (below 0x4000) is kept; two classes naming one graphic keep the first by file name.
$rows = @{}
$conflicts = 0
foreach ($dir in @('Weapons', 'Armor')) {
    foreach ($file in (Get-ChildItem (Join-Path $ServUoRoot "Scripts/Items/Equipment/$dir") -Recurse -Filter '*.cs' | Sort-Object FullName)) {
        $text = [IO.File]::ReadAllText($file.FullName)
        foreach ($cls in [regex]::Matches($text, '(?s)((?:\[[^\]]*\]\s*)*)public\s+(?:abstract\s+)?class\s+(\w+)\s*:\s*\w+(.*?)(?=(?:\[[^\]]*\]\s*)*public\s+(?:abstract\s+)?class\s|\z)')) {
            $body = $cls.Groups[3].Value
            $min = [regex]::Match($body, 'InitMinHits\s*\{\s*get\s*\{\s*return\s+(\d+)')
            $max = [regex]::Match($body, 'InitMaxHits\s*\{\s*get\s*\{\s*return\s+(\d+)')
            if (-not $min.Success -or -not $max.Success) { continue }
            $graphics = [Collections.Generic.List[int]]::new()
            foreach ($m in [regex]::Matches($cls.Groups[1].Value, '0x[0-9A-Fa-f]+')) { $graphics.Add([Convert]::ToInt32($m.Value, 16)) }
            $ctor = [regex]::Match($body, 'public\s+' + $cls.Groups[2].Value + '\s*\(\s*\)\s*:\s*base\s*\(\s*(0x[0-9A-Fa-f]+)')
            if ($ctor.Success) { $graphics.Add([Convert]::ToInt32($ctor.Groups[1].Value, 16)) }
            foreach ($g in ($graphics | Select-Object -Unique)) {
                if ($g -ge 0x4000) { continue }
                $value = [int]$min.Groups[1].Value * 65536 + [int]$max.Groups[1].Value
                if ($rows.ContainsKey($g)) { if ($rows[$g] -ne $value) { $conflicts++ }; continue }
                $rows[$g] = $value
            }
        }
    }
}
if ($rows.Count -lt 100) { throw "only $($rows.Count) graphics with durability" }
$out = [Collections.Generic.List[string]]::new()
$out.Add('Chapter: DurabilityData')
$out.Add('')
$out.Add(' Generated by import-durability.ps1 from ServUO Scripts/Items/Equipment Weapons and Armor (GPL-2.0); do not edit by')
$out.Add(' hand. A weapon or armour graphic answers its InitMinHits * 65536 + InitMaxHits; 0 is a graphic with no durability.')
$out.Add('  dur-range : Integer -> Integer')
$keys = @($rows.Keys | Sort-Object)
$out.Add("  dur-range (graphic) = if graphic == $($keys[0]) then $($rows[$keys[0]])")
for ($i = 1; $i -lt $keys.Count; $i++) { $out.Add("    else if graphic == $($keys[$i]) then $($rows[$keys[$i]])") }
$out.Add('    else 0')
[IO.File]::WriteAllText($Output, (($out -join "`r`n") + "`r`n"))
"graphics=$($rows.Count) conflicts=$conflicts -> $Output"
