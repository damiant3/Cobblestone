import {readFileSync,writeFileSync,mkdirSync,existsSync,createReadStream} from 'node:fs';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync,spawnSync} from 'node:child_process';

const repo=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const out=process.argv[2]&&resolve(process.argv[2]);
const width=Number(process.argv[3]||1024),height=Number(process.argv[4]||1024);
const sampler=Number(process.argv[5]||0);
const samplerNames=['Euler','DPM++ SDE','DPM++ 2M','DPM++ 2M SDE','DPM++ 2M SDE Heun','DPM++ 2S a','DPM++ 3M SDE'];
if(!Number.isInteger(sampler)||sampler<0||sampler>=samplerNames.length)throw new Error('Unsupported reference sampler');
const imageName=sampler===0?'euler-reference.png':'dpm-reference.png';
if(!out)throw new Error('Usage: node apps/diffusion/build-sdxl-reference.mjs new-output-directory [width height sampler-id]');
if(!['1024x1024','1344x768','768x1344'].includes(`${width}x${height}`))throw new Error('Unsupported reference preset');
if(/\s/.test(out))throw new Error('VM sidecar output path must not contain whitespace');
if(existsSync(out))throw new Error('Reference output directory already exists');
mkdirSync(out,{recursive:true});
const source=join(repo,'build/sdxl-browser-reference.codex'),kernel=join(repo,'seed/Codex.cdx');
const checkpoint=join(repo,'build-output/diffusion-models/dreamshaperXL_lightningDPMSDE.safetensors');
const hash=async path=>{const h=createHash('sha256');for await(const b of createReadStream(path))h.update(b);return h.digest('hex');};
const bytesHash=b=>createHash('sha256').update(b).digest('hex');
const evidence={checkpointSha256:await hash(checkpoint),compilerSha256:await hash(kernel),nativeSourceSha256:await hash(source)};
const original=readFileSync(source,'utf8');
if(!['ti-steps = 6','ti-cfg = 2.0','ti-seed = 7201','ti-scheduler = 2'].every(s=>original.includes(s)))throw new Error('Reference settings template changed');
if(!original.includes('Size: 1024x1024')||!original.includes('ti-width = 1024, ti-height = 1024'))throw new Error('Reference template changed');
if(!original.includes('ti-sampler = ti-euler')||!original.includes('Sampler: Euler,')||!original.includes('ti-out = "euler-reference.png"'))throw new Error('Sampler template changed');
const generated=original.replace('Size: 1024x1024',`Size: ${width}x${height}`).replace('ti-width = 1024, ti-height = 1024',`ti-width = ${width}, ti-height = ${height}`).replace('ti-sampler = ti-euler',`ti-sampler = ${sampler}`).replace('Sampler: Euler,',`Sampler: ${samplerNames[sampler]},`).replace('ti-out = "euler-reference.png"',`ti-out = "${imageName}"`);
const generatedPath=join(out,'reference.codex');writeFileSync(generatedPath,generated);
evidence.width=width;evidence.height=height;evidence.generatedSourceSha256=bytesHash(Buffer.from(generated));
evidence.sampler=sampler;evidence.samplerName=samplerNames[sampler];evidence.imageName=imageName;
const memory=()=>{const value=JSON.parse(execFileSync('pwsh',['-NoProfile','-Command','Get-CimInstance Win32_OperatingSystem | Select-Object FreePhysicalMemory,FreeVirtualMemory | ConvertTo-Json -Compress'],{encoding:'utf8',windowsHide:true}));if(value.FreePhysicalMemory<=1572864)throw new Error('Insufficient free RAM for one guest');return value;};
const run=(script,args,label)=>{
  const result=spawnSync('pwsh',['-NoProfile','-File',join(repo,script),...args],{cwd:repo,encoding:'utf8',windowsHide:true,maxBuffer:16777216,stdio:['ignore','pipe','pipe']});
  writeFileSync(join(out,label+'.stdout'),result.stdout||'');writeFileSync(join(out,label+'.stderr'),result.stderr||'');
  if(result.stdout)console.log(result.stdout.trim());if(result.stderr)console.error(result.stderr.trim());
  if(result.error)throw result.error;if(result.status!==0)throw new Error(label+' failed: '+result.status);
};
evidence.compileMemory=memory();
run('build/compile.ps1',['-Src',generatedPath,'-Out',join(out,'reference.cdx'),'-Log',join(out,'compile.log'),'-Kernel',kernel],'compile');
run('build/mint-clip-bpe-disk.ps1',['-Out',join(out,'clip.img')],'mint');
const disk=readFileSync(join(out,'clip.img')),vlen=disk.readUInt32LE(0),mlen=disk.readUInt32LE(4),mstart=(1+Math.ceil(vlen/512))*512;
if(vlen<1||mlen<1||512+vlen>disk.length||mstart+mlen>disk.length)throw new Error('Tokenizer disk layout differs');
evidence.vocabSha256=bytesHash(disk.subarray(512,512+vlen));
evidence.mergesSha256=bytesHash(disk.subarray(mstart,mstart+mlen));
evidence.tokenizerDiskSha256=bytesHash(disk);
evidence.nativeCdxSha256=await hash(join(out,'reference.cdx'));
writeFileSync(join(out,'reference.vmargs'),'-gpu-files build-output/diffusion-models\n-gpu-out '+out.replaceAll('\\','/')+'\n');
evidence.runMemory=memory();
const started=performance.now();
run('build/test-run.ps1',['-Kernel',join(out,'reference.cdx'),'-OutFile',join(out,'result.txt'),'-DiskFile',join(out,'clip.img'),'-VmArgsFile',join(out,'reference.vmargs')],'run');
evidence.seconds=(performance.now()-started)/1000;
evidence.nativeResult=readFileSync(join(out,'result.txt'),'utf8').trim();
if(!new RegExp(`^png ${width}x${height}: [0-9]+ bytes$`).test(evidence.nativeResult))throw new Error('Native render returned failure text');
const image=readFileSync(join(out,imageName));
if(image.subarray(0,8).toString('hex')!=='89504e470d0a1a0a'||image.readUInt32BE(16)!==width||image.readUInt32BE(20)!==height)throw new Error('Native render did not produce the expected PNG');
if(await hash(checkpoint)!==evidence.checkpointSha256||await hash(kernel)!==evidence.compilerSha256||await hash(source)!==evidence.nativeSourceSha256||await hash(generatedPath)!==evidence.generatedSourceSha256)throw new Error('Native reference inputs moved during rendering');
evidence.imageSha256=bytesHash(image);evidence.nativeExit=0;
writeFileSync(join(out,'reference-evidence.json'),JSON.stringify(evidence,null,2)+'\n');
console.log(JSON.stringify(evidence));
